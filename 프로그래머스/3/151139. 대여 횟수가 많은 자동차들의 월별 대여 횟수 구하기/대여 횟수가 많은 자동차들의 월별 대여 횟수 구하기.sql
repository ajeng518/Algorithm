SELECT
        MONTH(H.START_DATE) AS MONTH,
        H.CAR_ID,
        COUNT(H.CAR_ID)AS RECORDS
FROM CAR_RENTAL_COMPANY_RENTAL_HISTORY H
WHERE H.CAR_ID 
        IN (SELECT HIS1.CAR_ID
            FROM CAR_RENTAL_COMPANY_RENTAL_HISTORY HIS1
            WHERE HIS1.START_DATE>='2022-08-01' AND HIS1.START_DATE<'2022-11-01'
            GROUP BY HIS1.CAR_ID
             HAVING COUNT(HIS1.CAR_ID) >=5
            )
    AND (H.START_DATE>='2022-08-01' AND H.START_DATE<'2022-11-01')
GROUP BY MONTH(H.START_DATE), H.CAR_ID
HAVING COUNT(*) > 0 
ORDER BY MONTH ASC, H.CAR_ID DESC
;